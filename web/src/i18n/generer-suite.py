"""Génère les namespaces restants, depuis les tables de la spécification."""

import io
import json
import os

LANGUES = ('fr', 'ar', 'en')


def ecrire(ns, table):
    for lg in LANGUES:
        manquantes = [c for c, t in table.items() if not t.get(lg)]
        if manquantes:
            raise SystemExit(f'{ns}/{lg} : sans traduction — {manquantes}')
        os.makedirs(f'locales/{lg}', exist_ok=True)
        io.open(f'locales/{lg}/{ns}.json', 'w', encoding='utf-8').write(
            json.dumps({c: t[lg] for c, t in table.items()},
                       ensure_ascii=False, indent=2, sort_keys=True) + '\n'
        )


